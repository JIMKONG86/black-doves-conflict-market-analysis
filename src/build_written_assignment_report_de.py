OUTPUT_FILE = (
    english_report.ROOT
    / "output"
    / "black_doves_written_assignment_report_de.html"
)


def main():
    data = english_report._load_data()
    charts = english_report._create_charts(data)
    _localize_charts(charts)
    script, divs = components(charts)
    english_html = english_report._report_html(data, script, divs)
    german_html = _translate_document(english_html)
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    temporary = OUTPUT_FILE.with_suffix(".html.tmp")
    temporary.write_text(german_html, encoding="utf-8")
    temporary.replace(OUTPUT_FILE)
    print(OUTPUT_FILE)
    return 0


