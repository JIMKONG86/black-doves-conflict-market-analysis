"""Build the German, offline written-assignment report.

The quantitative content is generated by the same functions as the English
submission report.  Only presentation text is localized; company names,
official source titles, formulas, dataset identifiers and machine-readable
status codes remain unchanged so that both editions stay directly auditable.
"""

