def _translate_document(document):
    document = document.replace('<html lang="en">', '<html lang="de">', 1)
    protected = re.compile(
        r"(<(?:script|style)\b.*?</(?:script|style)>)",
        flags=re.IGNORECASE | re.DOTALL,
    )
    parts = protected.split(document)
    for index in range(0, len(parts), 2):
        parts[index] = re.sub(r">([^<>]+)<", _translate_node, parts[index])
    translated = "".join(parts)
    language_note = (
        '<p class="note"><strong>Sprachhinweis.</strong> Unternehmensnamen, '
        "Formeln, Datensatz-IDs, maschinenlesbare Statuscodes und verlinkte "
        "Originaltitel bleiben unverändert, damit die deutsche und die "
        "englische Fassung direkt überprüfbar bleiben.</p>"
    )
    translated = translated.replace("</header>", language_note + "\n</header>", 1)
    return re.sub(r"[ \t]+$", "", translated, flags=re.MULTILINE)


def _translate_node(match):
    original = match.group(1)
    leading = original[: len(original) - len(original.lstrip())]
    trailing = original[len(original.rstrip()) :]
    value = html_module.unescape(original.strip())
    translated = TRANSLATIONS.get(value)
    if translated is None:
        for pattern, replacement in REGEX_TRANSLATIONS:
            if pattern.fullmatch(value):
                translated = pattern.sub(replacement, value)
                break
    if translated is None:
        return ">" + original + "<"
    escaped = html_module.escape(translated, quote=False)
    return ">" + leading + escaped + trailing + "<"


